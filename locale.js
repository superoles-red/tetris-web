/** Язык интерфейса по локали браузера (ru/en), иначе английский. */
export function preferredLanguage() {
  const tags = [];
  try {
    if (typeof navigator !== 'undefined') {
      if (Array.isArray(navigator.languages)) tags.push(...navigator.languages);
      if (typeof navigator.language === 'string') tags.push(navigator.language);
    }
  } catch { /* Some environments throw on navigator access. */ }
  for (const tag of tags) {
    if (typeof tag !== 'string') continue;
    const language = tag.split('-')[0].toLowerCase();
    if (language === 'ru' || language === 'en') return language;
  }
  return 'en';
}

/** Подставляет {name}-параметры в строку локали. */
export function formatText(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (match, key) => (
    Object.hasOwn(params, key) ? String(params[key]) : match
  ));
}
