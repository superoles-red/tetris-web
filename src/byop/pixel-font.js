// Наш пиксельный шрифт для русского интерфейса.
//
// Кириллица собирается из английских букв (см. LATIN) так, чтобы стиль
// совпадал с английским шрифтом игры: одинаковые буквы берём напрямую,
// остальные достраиваем из частей (Й = И + дуга, Ж = два K, П = два L,
// Ф = два P, З = цифра 3 и т.д.). Ничего из русского картриджа (PSCD)
// здесь не используется — у него другой, более округлый шрифт.
//
// Формат глифа: 9 строк по 8 символов (`#` — пиксель, `.` — пусто):
//   0 — верхние знаки (точки Ё, дуга Й), 1..7 — буква, 8 — нижний хвост.

