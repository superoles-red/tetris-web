// Пиксельный шрифт оболочки для русского интерфейса.
//
// Это НАШ рисунок: кириллица нарисована по образцу английского шрифта игры
// (та же высота в 7 строк, толщина штриха 2 px, те же пропорции), чтобы RU и
// EN выглядели одинаково. Глифы из русского картриджа (PSCD) не используются:
// там другой, более округлый и мелкий шрифт.
//
// Формат глифа: 9 строк по 8 символов (`#` — пиксель, `.` — пусто):
//   строка 0 — верхние знаки (точки Ё, бревис Й),
//   строки 1–7 — сама буква (базовая линия — низ строки 7),
//   строка 8 — нижние хвосты (Ц, Щ) ниже базовой линии.

/**
 * Глифы нарисованы в «широкой» сетке 8 px, как в русском картридже; чтобы
 * буквы не слипались и совпадали по ширине с английским шрифтом, сжимаем
 * строку на один пиксель: убираем одну пустую колонку перед правым штрихом.
 */
function fitToLatinGrid(row) {
  if (row.length !== 8) return row;
  if (row === '########') return '#######.';
  const gap = row.indexOf('..');
  if (gap <= 0) return row;
  return row.slice(0, gap) + row.slice(gap + 1) + '.';
}

/** Собирает 9 строк из 7 строк «тела» и необязательных верх/низ. */
function glyph(body, accents = {}) {
  const rows = ['........', ...body.map(fitToLatinGrid), accents.bottom ? fitToLatinGrid(accents.bottom) : '........'];
  if (accents.top) rows[0] = fitToLatinGrid(accents.top);
  return rows;
}

