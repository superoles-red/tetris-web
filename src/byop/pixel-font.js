// --- операции над глифами ---------------------------------------------------
const overlay = (...layers) => {
  const out = [];
  for (let y = 0; y < 7; y++) {
    let bits = 0;
    for (const layer of layers) {
      for (let x = 0; x < W; x++) if (layer[y]?.[x] === '#') bits |= 1 << (7 - x);
    }
    out.push(bits);
  }
  return out.map((bits) => Array.from({ length: W }, (_, x) => ((bits >> (7 - x)) & 1 ? '#' : '.')).join(''));
};
const mirrorH = (rows) => rows.map((r) => r.split('').reverse().join(''));
const flipV = (rows) => rows.slice().reverse();
/** Кириллица: одинаковые буквы берём из латиницы, остальные достраиваем. */
function buildCyrillic() {
  const L = LATIN;
  const g = (rows) => glyphBody(rows);
  const withTail = (rows, tail) => {
    const body = rows.map(row);
    return ['........', ...body, row(tail)];
  };
  return {
    'А': g(L.A),
    'Б': g(['######..', '##......', '##......', '#####...', '##..##..', '##..##..', '#####...']),
    'В': g(L.B),
    'Г': g(flipV(L.L)),
    'Д': g(['..#####.', '..##.##.', '..##.##.', '..##.##.', '..##.##.', '########', '##....##']),
    'Е': g(L.E),
    'Ё': (() => { const e = g(L.E); e[0] = '..#..#..'; return e; })(),
    'Ж': g(['##.##.##', '##.##.##', '##.##.##', '.######.', '##.##.##', '##.##.##', '##.##.##']),
    'З': g(DIGITS[3]),
    'И': g(mirrorH(L.N)),
    'Й': (() => { const rows = g(mirrorH(L.N)); rows[0] = '..####..'; return rows; })(),
    'К': g(L.K),
    'Л': g(['..####..', '.##..##.', '.##..##.', '##...##.', '##...##.', '##...##.', '##...##.']),
    'М': g(L.M),
    'Н': g(L.H),
    'О': g(L.O),
    'П': g(overlay(flipV(L.L), mirrorH(flipV(L.L)))),
    'Р': g(L.P),
    'С': g(L.C),
    'Т': g(L.T),
    'У': g(L.Y),
    'Ф': g(overlay(L.O, Array(7).fill('...##...'))),
    'Х': g(L.X),
    'Ц': withTail(overlay(overlay(flipV(L.L), mirrorH(flipV(L.L))), ['........', '........', '........', '........', '........', '........', '########']), '......##'),
    'Ч': g(['##....##', '##....##', '##....##', '.#######', '.....##.', '.....##.', '.....##.']),
    'Ш': g(overlay(overlay(flipV(L.L), mirrorH(flipV(L.L))), ['...##...', '...##...', '...##...', '...##...', '...##...', '...##...', '########'])),
    'Щ': withTail(overlay(overlay(flipV(L.L), mirrorH(flipV(L.L))), ['...##...', '...##...', '...##...', '...##...', '...##...', '...##...', '########']), '......##'),
    'Ъ': g(['######..', '..##....', '..##....', '..#####.', '..##..##', '..##..##', '..#####.']),
    'Ы': g(overlay(['##......', '##......', '##......', '######..', '##...##.', '##...##.', '######..'], ['......##', '......##', '......##', '......##', '......##', '......##', '......##'])),
    'Ь': g(['##......', '##......', '##......', '######..', '##...##.', '##...##.', '######..']),
    'Э': g(mirrorH(DIGITS[3])),
    'Ю': g(['##.####.', '##.##.##', '##.##.##', '##.##.##', '##.##.##', '##.##.##', '##.####.']),
    'Я': g(mirrorH(L.R)),
  };
}

/** Пиксельные глифы, которые рисуем сами (9 строк на глиф). */
export const BUILTIN_GLYPHS = new Map();
for (const [ch, body] of Object.entries({ ...DIGITS, ...buildCyrillic() })) BUILTIN_GLYPHS.set(ch, body);

/** Английские буквы нашего рисунка (для русского интерфейса тоже). */
export const BUILTIN_LATIN = new Map();
